import {readFile,mkdir,writeFile,copyFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
let page=await readFile(new URL('src/index.html',root),'utf8');
const style=await readFile(new URL('src/style.css',root),'utf8');
const client=await readFile(new URL('src/client.js',root),'utf8');
page=page.replace('/*STYLE*/',()=>style).replace('/*CLIENT*/',()=>client);
const server=await readFile(new URL('worker/index.js',root),'utf8');
await mkdir(new URL('dist/server/',root),{recursive:true});await mkdir(new URL('dist/.openai/',root),{recursive:true});
await writeFile(new URL('dist/server/index.js',root),server.replace('const PAGE = "__PAGE__";',()=> 'const PAGE = '+JSON.stringify(page)+';'));
await copyFile(new URL('.openai/hosting.json',root),new URL('dist/.openai/hosting.json',root));
console.log('Built self-contained CaseRoom Worker.');
